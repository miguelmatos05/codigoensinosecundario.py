
#%% if
value = int(input("value="))
if value > 0:
    print("Positive")
print("end") 
    
#%% if else
value = int(input("value="))
if value > 0:
    print("Positive")
else:
    print("Negative")
print("end") 

#%% if elif else
value = int(input("value="))
if value > 0:
    print("Positive")
elif value == 0:
    print("Zero")
else:
    print("Negative")
print("end") 